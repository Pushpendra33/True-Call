fn generate_keypair() -> (SigningKey, String) {
    let mut secret = [0u8; 32];
    getrandom::getrandom(&mut secret).expect("RNG fail");
    let sk = SigningKey::from_bytes(&secret).expect("invalid key");
    let pk_hex = hex::encode(sk.verifying_key().to_bytes());
    (sk, pk_hex)
}

